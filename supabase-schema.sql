-- 7. WORKOUT SETS TABLE (Detailed per-set tracking with individual weights/reps)
CREATE TABLE IF NOT EXISTS public.workout_sets (
    id TEXT PRIMARY KEY,
    log_id BIGINT,
    exercise TEXT NOT NULL,
    set_number INTEGER NOT NULL DEFAULT 1,
    reps INTEGER NOT NULL DEFAULT 10,
    weight_kg NUMERIC NOT NULL DEFAULT 60.0,
    rpe NUMERIC DEFAULT 7.5,
    user_id TEXT NOT NULL DEFAULT 'user-athlete-1',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ==========================================
-- ROW LEVEL SECURITY (RLS) & ACCESS CONTROL
-- ==========================================

ALTER TABLE public.todos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.history_records ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.calendar_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.google_calendar_connections ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.workout_logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.exercises ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.workout_sets ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public full access on todos" ON public.todos FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);
CREATE POLICY "Allow public full access on history_records" ON public.history_records FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);
CREATE POLICY calendar_events_owner_access ON public.calendar_events FOR ALL TO authenticated USING (user_id = (SELECT auth.uid())) WITH CHECK (user_id = (SELECT auth.uid()));
CREATE POLICY google_calendar_connections_owner_access ON public.google_calendar_connections FOR ALL TO authenticated USING (user_id = (SELECT auth.uid())) WITH CHECK (user_id = (SELECT auth.uid()));
CREATE POLICY "Allow public full access on workout_logs" ON public.workout_logs FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);
CREATE POLICY "Allow public full access on user_profiles" ON public.user_profiles FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);
CREATE POLICY "Allow public full access on exercises" ON public.exercises FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);
CREATE POLICY "Allow public full access on workout_sets" ON public.workout_sets FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

GRANT ALL ON ALL TABLES IN SCHEMA public TO anon, authenticated;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated;

REVOKE ALL ON TABLE public.calendar_events, public.google_calendar_connections FROM anon, authenticated;
