-- Fitness AI workout schema migration.
-- Run once in the Supabase SQL Editor before deploying the FastAPI changes.
-- Existing test workout data is retained in legacy_* tables; Supabase Auth users are untouched.

BEGIN;

ALTER TABLE public.exercises
    ADD COLUMN IF NOT EXISTS user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE;
CREATE INDEX IF NOT EXISTS ix_exercises_user_id ON public.exercises(user_id);

DO $$
BEGIN
    IF to_regclass('public.workout_logs') IS NOT NULL
       AND to_regclass('public.legacy_workout_logs') IS NULL THEN
        ALTER TABLE public.workout_logs RENAME TO legacy_workout_logs;
    END IF;
    IF to_regclass('public.workout_sets') IS NOT NULL
       AND to_regclass('public.legacy_workout_sets') IS NULL THEN
        ALTER TABLE public.workout_sets RENAME TO legacy_workout_sets;
    END IF;
    IF to_regclass('public.history_records') IS NOT NULL
       AND to_regclass('public.legacy_history_records') IS NULL THEN
        ALTER TABLE public.history_records RENAME TO legacy_history_records;
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.workout_sessions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    completed_at TIMESTAMPTZ,
    notes TEXT NOT NULL DEFAULT '',
    mood INTEGER NOT NULL DEFAULT 8 CHECK (mood BETWEEN 1 AND 10),
    energy INTEGER NOT NULL DEFAULT 8 CHECK (energy BETWEEN 1 AND 10),
    sleep_quality INTEGER NOT NULL DEFAULT 8 CHECK (sleep_quality BETWEEN 1 AND 10),
    bodyweight_kg NUMERIC(7, 2) CHECK (bodyweight_kg IS NULL OR bodyweight_kg BETWEEN 20 AND 300)
    ,CONSTRAINT uq_workout_sessions_id_user UNIQUE (id, user_id)
);

CREATE INDEX IF NOT EXISTS ix_workout_sessions_user_id ON public.workout_sessions(user_id);
CREATE INDEX IF NOT EXISTS ix_workout_sessions_started_at ON public.workout_sessions(started_at DESC);
CREATE INDEX IF NOT EXISTS ix_workout_sessions_user_started_at
    ON public.workout_sessions(user_id, started_at DESC);

CREATE TABLE IF NOT EXISTS public.workout_logs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id UUID NOT NULL,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    exercise_id TEXT REFERENCES public.exercises(id) ON DELETE SET NULL,
    exercise TEXT NOT NULL,
    exercise_type VARCHAR(32) NOT NULL DEFAULT 'strength',
    muscle_group VARCHAR(32) NOT NULL DEFAULT 'full_body',
    sets_count INTEGER NOT NULL CHECK (sets_count > 0),
    total_reps INTEGER NOT NULL CHECK (total_reps >= 0),
    rpe NUMERIC(3, 1) CHECK (rpe IS NULL OR rpe BETWEEN 1 AND 10),
    notes TEXT NOT NULL DEFAULT '',
    form_score NUMERIC(4, 2) CHECK (form_score IS NULL OR form_score BETWEEN 0 AND 10),
    range_of_motion NUMERIC(5, 2) CHECK (range_of_motion IS NULL OR range_of_motion BETWEEN 0 AND 100),
    device_data JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_workout_logs_id_user UNIQUE (id, user_id),
    CONSTRAINT fk_workout_logs_session_owner FOREIGN KEY (session_id, user_id)
        REFERENCES public.workout_sessions(id, user_id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS ix_workout_logs_session_id ON public.workout_logs(session_id);
CREATE INDEX IF NOT EXISTS ix_workout_logs_exercise_id ON public.workout_logs(exercise_id);
CREATE INDEX IF NOT EXISTS ix_workout_logs_exercise_lower ON public.workout_logs(lower(exercise));

CREATE TABLE IF NOT EXISTS public.workout_sets (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    log_id INTEGER NOT NULL,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    set_number INTEGER NOT NULL CHECK (set_number > 0),
    reps INTEGER NOT NULL CHECK (reps >= 0),
    weight_kg NUMERIC(8, 2) NOT NULL DEFAULT 0 CHECK (weight_kg >= 0),
    rpe NUMERIC(3, 1) CHECK (rpe IS NULL OR rpe BETWEEN 1 AND 10),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_workout_sets_log_owner FOREIGN KEY (log_id, user_id)
        REFERENCES public.workout_logs(id, user_id) ON DELETE CASCADE,
    CONSTRAINT uq_workout_sets_log_set_number UNIQUE (log_id, set_number)
);

CREATE INDEX IF NOT EXISTS ix_workout_sets_log_id ON public.workout_sets(log_id);

-- FastAPI uses its private server-side database connection. Do not expose workout
-- or profile data to mobile clients through Supabase's Data API.
DO $$
DECLARE
    table_name TEXT;
    policy_record RECORD;
BEGIN
    FOREACH table_name IN ARRAY ARRAY[
        'workout_sessions', 'workout_logs', 'workout_sets', 'legacy_workout_logs',
        'legacy_workout_sets', 'legacy_history_records', 'history_records',
        'user_profiles', 'calendar_events', 'todos', 'exercises'
    ] LOOP
        IF to_regclass(format('public.%I', table_name)) IS NOT NULL THEN
            EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', table_name);
            EXECUTE format('REVOKE ALL ON TABLE public.%I FROM anon, authenticated', table_name);
        END IF;
    END LOOP;

    FOR policy_record IN
        SELECT schemaname, tablename, policyname
        FROM pg_policies
        WHERE schemaname = 'public'
          AND tablename = ANY (ARRAY[
              'workout_sessions', 'workout_logs', 'workout_sets',
              'legacy_workout_logs', 'legacy_workout_sets', 'legacy_history_records',
              'history_records', 'user_profiles', 'calendar_events', 'todos', 'exercises'
          ])
    LOOP
        EXECUTE format(
            'DROP POLICY %I ON %I.%I',
            policy_record.policyname,
            policy_record.schemaname,
            policy_record.tablename
        );
    END LOOP;
END $$;

REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM anon, authenticated;

COMMIT;
